void MidiNetworkApiTests::TestHostCreationConfigGeneratesUniqueIds()
{
    // No service needed. The id is generated in the API, so a caller can read it back
    // immediately and use it to remove the host later.
    const int count = 50;

    std::vector<winrt::guid> seen;

    for (int i = 0; i < count; i++)
    {
        MidiNetworkHostCreationConfig config;

        auto id = config.HostId();

        VERIFY_ARE_NOT_EQUAL(winrt::guid{}, id);

        for (auto const& existing : seen)
        {
            VERIFY_ARE_NOT_EQUAL(existing, id);
        }

        seen.push_back(id);
    }

    VERIFY_ARE_EQUAL((size_t)count, seen.size());
}

void MidiNetworkApiTests::TestGeneratedHostIdSurvivesRoundTripToService()
{
    SKIP_IF_NO_NETWORK_TRANSPORT();

    // The id the API generated must be the one the service stores and hands back, otherwise
    // the caller has no way to find the host it just created.
    auto hostId = CreateTestHost(MakeUniqueSuffix());

    VERIFY_ARE_NOT_EQUAL(winrt::guid{}, hostId);

    auto cleanup = wil::scope_exit([&] { RemoveTestHost(hostId); });

    VerifyHostAppeared(hostId);

    bool found{ false };

    for (auto const& host : MidiNetworkTransportManager::GetConfiguredHosts())
    {
        if (host.HostId() == hostId)
        {
            found = true;
            break;
        }
    }

    VERIFY_IS_TRUE(found);

    // and it is still the same id on a second read, so nothing is regenerating it
    bool foundAgain{ false };

    for (auto const& host : MidiNetworkTransportManager::GetConfiguredHosts())
    {
        if (host.HostId() == hostId)
        {
            foundAgain = true;
            break;
        }
    }

    VERIFY_IS_TRUE(foundAgain);
}


