void MidiNetworkApiTests::TestEnsureCompliantServiceInstanceNameStripsPeriods()
{
    // A period would split this into two DNS labels, so it cannot survive. Periods are removed
    // rather than substituted, so nothing the caller did not type appears in the result.
    VERIFY_ARE_EQUAL(
        winrt::hstring{ L"contososynth1" },
        MidiNetworkHostCreationConfig::EnsureCompliantServiceInstanceName(L"contoso.synth.1"));

    // including the case where someone passes the fully qualified name by mistake
    VERIFY_ARE_EQUAL(
        winrt::hstring{ L"bomebox-8q6d2z-1_midi2_udplocal" },
        MidiNetworkHostCreationConfig::EnsureCompliantServiceInstanceName(L"bomebox-8q6d2z-1._midi2._udp.local"));
}

void MidiNetworkApiTests::TestEnsureCompliantServiceInstanceNameKeepsSpacesAndUnicode()
{
    // RFC 6763 treats the instance name as user-visible text, so these are all legal.
    VERIFY_ARE_EQUAL(
        winrt::hstring{ L"Pete's Studio Rig" },
        MidiNetworkHostCreationConfig::EnsureCompliantServiceInstanceName(L"Pete's Studio Rig"));

    VERIFY_ARE_EQUAL(
        winrt::hstring{ L"Sala de M\u00fasica" },
        MidiNetworkHostCreationConfig::EnsureCompliantServiceInstanceName(L"Sala de M\u00fasica"));

    // leading and trailing whitespace is not meaningful and gets trimmed
    VERIFY_ARE_EQUAL(
        winrt::hstring{ L"Studio A" },
        MidiNetworkHostCreationConfig::EnsureCompliantServiceInstanceName(L"   Studio A   "));
}

void MidiNetworkApiTests::TestEnsureCompliantServiceInstanceNameStripsControlCharacters()
{
    VERIFY_ARE_EQUAL(
        winrt::hstring{ L"Studio A" },
        MidiNetworkHostCreationConfig::EnsureCompliantServiceInstanceName(L"Stu\r\ndio\t A"));

    // an input made entirely of illegal characters leaves nothing behind, and the caller
    // is expected to treat an empty result as "pick something else"
    VERIFY_ARE_EQUAL(
        winrt::hstring{ L"" },
        MidiNetworkHostCreationConfig::EnsureCompliantServiceInstanceName(L"..."));
}

void MidiNetworkApiTests::TestEnsureCompliantServiceInstanceNameLimitsToLabelByteCount()
{
    const size_t maxBytes = 63;

    auto longAscii = MidiNetworkHostCreationConfig::EnsureCompliantServiceInstanceName(
        winrt::hstring{ RepeatedString(L'A', 200) });

    VERIFY_ARE_EQUAL(maxBytes, (size_t)longAscii.size());

    // The limit is bytes once encoded, not characters, so multi-byte text has to come back
    // shorter in characters than the ASCII case rather than the same length.
    std::wstring multiByte;
    for (int i = 0; i < 200; i++)
    {
        multiByte += L"\u00e9";        // two bytes each in UTF-8
    }

    auto longUnicode = MidiNetworkHostCreationConfig::EnsureCompliantServiceInstanceName(winrt::hstring{ multiByte });

    VERIFY_IS_LESS_THAN((size_t)longUnicode.size(), maxBytes);
    VERIFY_IS_GREATER_THAN((size_t)longUnicode.size(), (size_t)0);

    // and it must never split a character in half
    for (auto const ch : std::wstring{ longUnicode.c_str() })
    {
        VERIFY_ARE_EQUAL(L'\u00e9', ch);
    }
}

